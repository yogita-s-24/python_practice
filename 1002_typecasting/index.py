# type casting : process of converting / changing from one data type to another

# integers

a = 10  # non-default value
b = 0  # default value

# integers to float
print(float(a))
print(float(b))

# int to complex
print(complex(a))
print(complex(b))

# int to bool
print(bool(a))
print(bool(b))

# integers can be converted to all other individual data types

###################################################################
# floats

a = 1.5  # non-default value
b = 0.0  # default

# float to int
print(int(a))
print(int(b))

# float to complex
print(complex(a))
print(complex(b))

# float to bool
print(bool(a))
print(bool(b))

# floats can be converted to all other individual data types

#################################################################
